"""Compact native layout; behavior remains in the main dialog."""

import c4d

from .native_ui import add_action


def build(dialog, ids):
    def action(identifier, label, help_text):
        return add_action(dialog, identifier, label, help_text)

    fit = c4d.BFH_SCALEFIT
    stretch = fit | c4d.BFV_SCALEFIT
    dialog.SetTitle("分子球棍生成器")
    dialog.GroupBegin(ids.ROOT_LAYOUT, stretch, cols=2)
    dialog.GroupSpace(12, 0)
    dialog.GroupBegin(10, stretch, cols=1)
    dialog.GroupBorderSpace(12, 12, 12, 12)
    dialog.GroupSpace(6, 8)
    dialog.GroupBegin(11, fit, cols=2)
    dialog.AddComboBox(ids.INPUT_KIND, c4d.BFH_FIT, initw=95)
    dialog.AddChild(ids.INPUT_KIND, 0, "名称／分子式")
    dialog.AddChild(ids.INPUT_KIND, 1, "SMILES")
    dialog.AddEditText(ids.INPUT, fit, initw=220)
    dialog.GroupEnd()
    dialog.GroupBegin(12, fit, cols=3)
    action(ids.RESOLVE, "查找", "查找名称或分子式；点击结构图片选择候选。")
    action(ids.PASTE, "粘贴", "从 ChemDraw 复制为 SMILES 后粘贴。")
    action(ids.IMPORT, "导入", "导入 CDXML、MOL 或 SDF 结构文件。")
    dialog.GroupEnd()
    dialog.GroupBegin(13, fit, cols=2)
    dialog.AddCheckbox(ids.COMMON, c4d.BFH_LEFT, 0, 0, "常用")
    dialog.AddCheckbox(ids.FAVORITES, c4d.BFH_LEFT, 0, 0, "收藏")
    dialog.GroupEnd()
    dialog.GroupBegin(20, fit, cols=4)
    action(ids.SAVE, "加入", "将当前结构、外观和平面分组保存到收藏；同结构更新预设。")
    action(ids.REMOVE, "移除", "移除所选收藏条目。")
    action(ids.IMPORT_LIBRARY, "导入收藏", "导入收藏 JSON；已有结构保留。")
    action(ids.EXPORT, "导出收藏", "导出含结构和缩略图的便携收藏。")
    dialog.GroupEnd()
    dialog.ScrollGroupBegin(14, stretch, c4d.SCROLLGROUP_VERT | c4d.SCROLLGROUP_AUTOVERT,
                            initw=360, inith=130)
    dialog.GroupBegin(ids.CARDS, fit | c4d.BFV_TOP, cols=2)
    dialog.GroupSpace(8, 8)
    dialog.GroupEnd()
    dialog.GroupEnd()
    dialog.GroupBegin(15, fit, cols=3)
    action(ids.PREVIOUS, "上一页", "显示上一页结构。")
    dialog.AddStaticText(ids.PAGE, c4d.BFH_CENTER, name="")
    action(ids.NEXT, "下一页", "显示下一页结构。")
    dialog.GroupEnd()
    dialog.AddStaticText(ids.SELECTED, fit, name="选择结构")
    dialog.AddStaticText(ids.WARNING, fit, name="")
    dialog.AddSeparatorH(0, fit)
    dialog.TabGroupBegin(30, fit, tabtype=c4d.TAB_TABS)
    dialog.GroupBegin(31, fit, cols=1, title="外观")
    dialog.GroupBorderSpace(0, 8, 0, 8)
    dialog.GroupSpace(6, 6)
    dialog.GroupBegin(23, fit, cols=2)
    action(ids.BALL_STICK, "球棍", "恢复球棍显示和之前的球大小；平面分组保留。")
    action(ids.SPACE_FILL, "填充", "按元素尺寸放大球，允许交叠；氢保留空间方向。")
    dialog.GroupEnd()
    dialog.GroupBegin(16, fit, cols=6)
    for label, identifier in (("球径", ids.ATOM_RADIUS), ("键径", ids.BOND_RADIUS), ("间距", ids.SPACING)):
        dialog.AddStaticText(ids.ATOM_LABEL if identifier == ids.ATOM_RADIUS else 0,
                             c4d.BFH_LEFT, name=label)
        dialog.AddEditNumberArrows(identifier, fit, initw=60)
    dialog.GroupEnd()
    dialog.GroupBegin(17, fit, cols=2)
    dialog.AddComboBox(ids.BOND_MODE, fit)
    dialog.AddChild(ids.BOND_MODE, 0, "多键")
    dialog.AddChild(ids.BOND_MODE, 1, "单棍")
    dialog.AddComboBox(ids.BOND_MATERIAL, fit)
    dialog.AddChild(ids.BOND_MATERIAL, 0, "统一键色")
    dialog.AddChild(ids.BOND_MATERIAL, 1, "元素键色")
    dialog.AddCheckbox(ids.HYDROGENS, c4d.BFH_LEFT, 0, 0, "显示氢")
    dialog.AddComboBox(ids.QUALITY, fit)
    for index, label in enumerate(("低精度", "中精度", "高精度")):
        dialog.AddChild(ids.QUALITY, index, label)
    dialog.GroupEnd()
    dialog.GroupBegin(18, fit, cols=4)
    dialog.AddStaticText(0, c4d.BFH_LEFT, name="键色")
    dialog.AddColorField(ids.BOND_COLOR, fit, initw=70, inith=20)
    dialog.AddComboBox(ids.ELEMENT, c4d.BFH_FIT, initw=60)
    for index, element in enumerate(ids.ELEMENTS):
        dialog.AddChild(ids.ELEMENT, index, "球 " + element)
    dialog.AddColorField(ids.ELEMENT_COLOR, fit, initw=70, inith=20)
    dialog.GroupEnd()
    action(ids.APPLY_COLOR, "应用球色", "设置所选元素的球材质颜色；键材质保持独立。点击更新应用。")
    dialog.GroupEnd()
    dialog.GroupBegin(32, fit, cols=4, title="收藏信息")
    dialog.GroupBorderSpace(0, 8, 0, 8)
    dialog.AddStaticText(0, c4d.BFH_LEFT, name="名称")
    dialog.AddEditText(ids.LABEL, fit, initw=130)
    dialog.AddStaticText(0, c4d.BFH_LEFT, name="分组")
    dialog.AddEditText(ids.CATEGORY, fit, initw=95)
    dialog.GroupEnd()
    dialog.GroupEnd()
    dialog.GroupBegin(19, fit, cols=3)
    action(ids.GENERATE, "生成", "在当前 C4D 文档中生成新分子，成功后计入常用次数。")
    action(ids.UPDATE, "更新", "更新所选分子的外观，保留根对象变换。")
    action(ids.READ_MODEL, "读取", "读取 C4D 中所选分子，进入编辑前先读取或生成模型。")
    dialog.GroupEnd()
    dialog.GroupBegin(24, fit, cols=2)
    dialog.AddCheckbox(ids.EDIT_MODE, c4d.BFH_LEFT, 0, 0, "平面编辑")
    action(ids.CANCEL, "取消", "取消正在处理的结构。")
    dialog.GroupEnd()
    dialog.GroupBegin(25, fit, cols=2)
    dialog.AddStaticText(ids.STATUS, fit, name="加载结构…")
    action(ids.DETAILS, "详情", "查看名称、分子式、SMILES 和结构提示。")
    dialog.GroupEnd()
    dialog.GroupEnd()
    dialog.GroupBegin(ids.EDITOR_GROUP, stretch, cols=1)
    dialog.GroupBorderSpace(0, 12, 12, 12)
    dialog.AddSubDialog(ids.EDITOR_SUB, stretch, initw=380, inith=450)
    from .atom_selector import AtomSelectionPanel
    dialog.editor = AtomSelectionPanel(dialog._apply_flatten, dialog._restore_3d,
                                       dialog._select_model_atoms, dialog._apply_plane_groups)
    if not dialog.AttachSubDialog(dialog.editor, ids.EDITOR_SUB):
        raise RuntimeError("无法嵌入平面编辑区")
    dialog.GroupEnd()
    dialog.GroupEnd()
    dialog.HideElement(ids.EDITOR_GROUP, True)
    return True
